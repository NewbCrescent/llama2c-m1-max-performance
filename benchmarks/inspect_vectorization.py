#!/usr/bin/env python3
"""Record Clang vectorization diagnostics and the hot matmul instructions."""

from __future__ import annotations

import argparse
import re
import subprocess
import tempfile
from pathlib import Path

from run_benchmarks import ROOT, checked_output, find_clang


def matmul_assembly(text: str) -> str:
    lines = text.splitlines()
    start = next(i for i, line in enumerate(lines) if re.match(r"^_?matmul:", line))
    end = len(lines)
    for i in range(start + 1, len(lines)):
        if lines[i].startswith("\t.globl") or lines[i].startswith(".globl") or lines[i].startswith("\t.size\tmatmul"):
            end = i
            break
    return "\n".join(lines[start:end])


def interesting_instructions(assembly: str) -> list[str]:
    markers = ("fmla", "fmadd", "fmul", "fadd", "ldp\tq", "ldr\tq")
    return [line.strip() for line in assembly.splitlines() if any(marker in line for marker in markers)][:32]


def compile_report(cc: Path, flags: list[str], directory: Path, name: str) -> dict[str, object]:
    assembly_path = directory / f"{name}.s"
    command = [
        str(cc),
        "-std=c11",
        "-march=native",
        *flags,
        "-Rpass=loop-vectorize",
        "-Rpass-missed=loop-vectorize",
        "-S",
        str(ROOT / "run.c"),
        "-o",
        str(assembly_path),
    ]
    completed = subprocess.run(command, cwd=ROOT, text=True, capture_output=True, check=True)
    assembly = matmul_assembly(assembly_path.read_text(encoding="utf-8"))
    return {
        "command": command,
        "diagnostics": completed.stderr.strip().splitlines(),
        "instructions": interesting_instructions(assembly),
        "vector_fma_count": len(re.findall(r"\bfmla", assembly)),
        "vector_multiply_count": len(re.findall(r"\bfmul(?:\.4s)?", assembly)),
        "scalar_add_count": len(re.findall(r"\bfadd\s", assembly)),
    }


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cc", help="Clang binary; defaults to Homebrew LLVM when available")
    parser.add_argument("--output", type=Path, default=ROOT / "docs" / "vectorization.md")
    args = parser.parse_args()
    cc = find_clang(args.cc)
    args.output = args.output.expanduser().resolve()

    source_lines = (ROOT / "run.c").read_text(encoding="utf-8").splitlines()
    scalar_line = max(i for i, line in enumerate(source_lines, 1) if "for (int j = 0; j < n; j++)" in line)

    with tempfile.TemporaryDirectory(prefix="fastollama-vectorization-") as temporary:
        directory = Path(temporary)
        strict = compile_report(cc, ["-O3"], directory, "strict")
        fast = compile_report(cc, ["-O3", "-ffast-math"], directory, "fast")

    def relevant_diagnostics(report: dict[str, object]) -> list[str]:
        matches = [
            line.replace(f"{ROOT}/", "")
            for line in report["diagnostics"]
            if f"run.c:{scalar_line}:" in line
        ]
        matches = list(dict.fromkeys(matches))
        return matches or ["No diagnostic emitted for the scalar dot-product line."]

    lines = [
        "# Clang vectorization inspection",
        "",
        f"Compiler: `{checked_output([str(cc), '--version']).splitlines()[0]}`",
        "",
        "Generated by `python3 benchmarks/inspect_vectorization.py`. The report compares the same scalar "
        "matmul source under standards-conforming `-O3` and `-O3 -ffast-math`.",
        "",
        "## What changed",
        "",
        "Both builds recognize vectorizable work. The strict build preserves the ordered floating-point "
        "reduction: it performs vector multiplies, extracts lanes, and accumulates them serially. With "
        "`-ffast-math`, Clang may reassociate the reduction, so it emits independent vector FMA accumulators "
        "and performs the horizontal reduction once after the loop. That instruction-level difference, not "
        "merely the presence of SIMD registers, explains the large throughput gap.",
        "",
        "## Compiler diagnostics",
        "",
        "Strict `-O3`:",
        "",
        "```text",
        *relevant_diagnostics(strict),
        "```",
        "",
        "`-O3 -ffast-math`:",
        "",
        "```text",
        *relevant_diagnostics(fast),
        "```",
        "",
        "## Hot-loop instruction excerpts",
        "",
        f"Strict counts: {strict['vector_fma_count']} vector FMA, {strict['vector_multiply_count']} vector multiply, "
        f"{strict['scalar_add_count']} scalar add instructions in the compiled `matmul` function.",
        "",
        "```asm",
        *strict["instructions"],
        "```",
        "",
        f"Fast-math counts: {fast['vector_fma_count']} vector FMA, {fast['vector_multiply_count']} vector multiply, "
        f"{fast['scalar_add_count']} scalar add instructions in the compiled `matmul` function.",
        "",
        "```asm",
        *fast["instructions"],
        "```",
        "",
        "Instruction counts are descriptive, not a performance metric; the end-to-end repeated benchmark is "
        "the source of performance claims.",
        "",
    ]
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
